const setTextInputRange = (sheet: XLSX.WorkSheet, columns: number[], maxRow = 500) => {
  columns.forEach((column) => {
    for (let row = 2; row <= maxRow; row += 1) {
      const address = XLSX.utils.encode_cell({ r: row - 1, c: column });
      sheet[address] = { t: "s", v: "", z: "@" };
    }
  });
};

const prepareDataSheet = (headers: readonly string[], widths: number[], textColumns: number[]) => {
  const sheet = XLSX.utils.aoa_to_sheet([[...headers]]);
  setTextInputRange(sheet, textColumns);
  sheet["!ref"] = XLSX.utils.encode_range({ s: { r: 0, c: 0 }, e: { r: 499, c: headers.length - 1 } });
  sheet["!cols"] = widths.map((wch) => ({ wch }));
  sheet["!autofilter"] = { ref: `A1:${XLSX.utils.encode_col(headers.length - 1)}1` };
  return sheet;
};

